#!/usr/bin/env python3
"""
Builds the moon pictures in server/icons/moon/.

Takes a map of the whole lunar surface (equirectangular, near side in the
middle), wraps it on a sphere, and lights it from the sun's direction for
each of 32 phases. The result is one small PNG per phase: 00 is the new
moon, 08 the first quarter, 16 the full moon, 24 the last quarter.
The pictures are for the northern hemisphere: a waxing moon is lit on the right.

    python3 tools/build-moon.py path/to/moon_map.jpg

A suitable map is examples/textures/planets/moon_1024.jpg from three.js
(made from NASA imagery). Needs numpy and Pillow.
"""
import sys
from pathlib import Path

import numpy as np
from PIL import Image

FRAMES = 32
SIZE = 360          # pixels, final
SS = 3              # supersampling
DARK = 52           # gray of the unlit side
OUT = Path(__file__).resolve().parent.parent / "server" / "icons" / "moon"


def main(map_path: str) -> None:
    surface = np.asarray(Image.open(map_path).convert("L"), dtype=np.float64) / 255
    h, w = surface.shape

    n = SIZE * SS
    axis = (np.arange(n) + 0.5) / n * 2 - 1
    x, y = np.meshgrid(axis * 1.02, -axis * 1.02)     # small margin around the disc
    r2 = x * x + y * y
    inside = r2 <= 1
    z = np.sqrt(np.clip(1 - r2, 0, 1))

    # Look up the surface under each pixel.
    lat = np.arcsin(np.clip(y, -1, 1))
    lon = np.arctan2(x, z)
    px = ((lon / (2 * np.pi) + 0.5) * w).astype(int) % w
    py = np.clip(((0.5 - lat / np.pi) * h).astype(int), 0, h - 1)
    tex = surface[py, px]

    # Stretch the contrast so the seas stand out on a 16-gray screen.
    lo, hi = np.percentile(tex[inside], [2, 98])
    tex = np.clip((tex - lo) / (hi - lo), 0, 1) ** 0.9
    lit_gray = 105 + tex * 145                        # 105..250
    dark_gray = DARK + tex * 22                       # a hint of surface in the shadow

    # Soft edge, and a thin dark rim so the lit limb stands out from white paper.
    r = np.sqrt(r2)
    alpha = np.clip((1 - r) * n / 2 / 1.02 + 0.5, 0, 1)
    rim = np.clip((r - 0.972) / 0.012, 0, 1)

    OUT.mkdir(parents=True, exist_ok=True)
    for i in range(FRAMES):
        a = 2 * np.pi * i / FRAMES
        sun = (np.sin(a), 0.0, -np.cos(a))
        facing = x * sun[0] + z * sun[2]
        light = np.clip(facing / 0.10 + 0.5, 0, 1)    # narrow, soft terminator
        gray = dark_gray + (lit_gray - dark_gray) * light
        gray = gray * (1 - rim) + 70 * rim

        la = np.stack([np.clip(gray, 0, 255), alpha * 255], axis=-1).astype(np.uint8)
        img = Image.fromarray(la, "LA").resize((SIZE, SIZE), Image.LANCZOS)
        img.save(OUT / f"{i:02d}.png", optimize=True)

    (OUT / "README.txt").write_text(
        "Moon phases, 00 = new moon to 31, rendered from a NASA-based surface map\n"
        "(three.js examples/textures/planets/moon_1024.jpg).\n"
        "Generated by tools/build-moon.py; do not edit by hand.\n"
    )
    print(f"wrote {FRAMES} pictures to {OUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
