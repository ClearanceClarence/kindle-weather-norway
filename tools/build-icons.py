#!/usr/bin/env python3
"""
Builds the bitmap icon sets in server/icons/ from their original SVG files.

You only need this to rebuild or add an icon set; the generated PNGs are
checked in. It needs Python 3 with Pillow, and the rsvg-convert program
(package "librsvg2-bin" on Debian and Ubuntu).

    python3 tools/build-icons.py SOURCES

SOURCES is a folder holding the icon projects:

    SOURCES/metno/       https://github.com/metno/weathericons            (MIT)
    SOURCES/meteocons/   the npm package @meteocons/svg-static, unpacked  (MIT)
    SOURCES/erikflowers/ https://github.com/erikflowers/weather-icons     (SIL OFL 1.1)

Every icon becomes a 256 x 256 PNG in shades of gray with transparency. The
grays are darkened so they stay visible on e-ink, which washes out light
tones.

Sets drawn by code ("outline" and "duotone") live in server/src/Canvas.php
and have no files here.
"""

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image, ImageChops

SIZE = 256
OUT = Path(__file__).resolve().parent.parent / "server" / "icons"

# The ten weather kinds the display knows (see parse_symbol in src/weather.php),
# and the file each set uses for them.
KINDS = {
    #  kind           Yr                    Meteocons               Erik Flowers
    "sun":          ("clearsky_day",       "clear-day",            "wi-day-sunny"),
    "moon":         ("clearsky_night",     "clear-night",          "wi-night-clear"),
    "partly":       ("partlycloudy_day",   "partly-cloudy-day",    "wi-day-cloudy"),
    "partly_night": ("partlycloudy_night", "partly-cloudy-night",  "wi-night-alt-cloudy"),
    "cloud":        ("cloudy",             "cloudy",               "wi-cloudy"),
    "rain":         ("rain",               "rain",                 "wi-rain"),
    "sleet":        ("sleet",              "sleet",                "wi-sleet"),
    "snow":         ("snow",               "snow",                 "wi-snow"),
    "thunder":      ("rainandthunder",     "thunderstorms-rain",   "wi-thunderstorm"),
    "fog":          ("fog",                "fog",                  "wi-fog"),
}


def render(svg: Path, size: int = SIZE * 2) -> Image.Image:
    """Rasterizes an SVG to RGBA."""
    with tempfile.NamedTemporaryFile(suffix=".png") as tmp:
        subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), "-a", str(svg), "-o", tmp.name], check=True)
        image = Image.open(tmp.name).convert("RGBA")
    square = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    square.paste(image, ((size - image.width) // 2, (size - image.height) // 2))
    return square


def to_gray(image: Image.Image, curve) -> Image.Image:
    """Converts colors to gray through a tone curve, keeping transparency."""
    alpha = image.getchannel("A")
    on_white = Image.new("RGBA", image.size, (255, 255, 255, 255))
    on_white.alpha_composite(image)
    gray = on_white.convert("L").point([max(0, min(255, int(curve(v)))) for v in range(256)])
    return Image.merge("LA", (gray, alpha))


def save_set(name: str, icons: dict, license_file: Path, note: str) -> None:
    """
    Crops every icon in the set by the same box (so their relative sizes are
    kept), scales to SIZE, and writes them with the set's license.
    """
    folder = OUT / name
    shutil.rmtree(folder, ignore_errors=True)
    folder.mkdir(parents=True)

    box = None
    for image in icons.values():
        b = image.getchannel("A").getbbox()
        if b:
            box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
    # Make the crop box square, centered on the content.
    side = max(box[2] - box[0], box[3] - box[1])
    cx, cy = (box[0] + box[2]) / 2, (box[1] + box[3]) / 2
    crop = (int(cx - side / 2), int(cy - side / 2), int(cx + side / 2), int(cy + side / 2))

    for icon_name, image in icons.items():
        image.crop(crop).resize((SIZE, SIZE), Image.LANCZOS).save(folder / f"{icon_name}.png", optimize=True)
    shutil.copy(license_file, folder / "LICENSE.txt")
    (folder / "README.txt").write_text(note + "\nGenerated by tools/build-icons.py; do not edit by hand.\n")
    print(f"{name}: {len(icons)} icons")


def build_yr(src: Path) -> None:
    """MET Norway's own icons: one per weather code, plus the ten kinds as a fallback."""
    darken = lambda v: 255 if v >= 250 else 255 * (v / 255) ** 1.9
    icons = {svg.stem: to_gray(render(svg), darken) for svg in sorted((src / "weather" / "svg").glob("*.svg"))}
    for kind, (yr, _, _) in KINDS.items():
        icons[kind] = icons[yr]
    save_set("yr", icons, src / "LICENSE", "Weather icons by Yr / MET Norway, converted to gray. https://github.com/metno/weathericons")


def build_meteocons(src: Path) -> None:
    """Meteocons in two tones: the gray fills of its "flat" style under the black lines of "monochrome"."""
    soften = lambda v: 255 if v >= 250 else (v - 100) * 0.72 + 112
    icons = {}
    for kind, (_, name, _) in KINDS.items():
        fill = render(src / "flat" / f"{name}.svg")
        line = render(src / "monochrome" / f"{name}.svg")
        gray_fill = to_gray(fill, soften)
        gray_line = to_gray(line, lambda v: v)
        gray = ImageChops.multiply(
            Image.composite(gray_fill.getchannel("L"), Image.new("L", fill.size, 255), gray_fill.getchannel("A")),
            Image.composite(gray_line.getchannel("L"), Image.new("L", line.size, 255), gray_line.getchannel("A")),
        )
        alpha = ImageChops.lighter(fill.getchannel("A"), line.getchannel("A"))
        icons[kind] = Image.merge("LA", (gray, alpha))
    save_set("meteocons", icons, src / "LICENSE", "Meteocons by Bas Milius, two-tone conversion. https://github.com/basmilius/weather-icons")


def build_bold(src: Path) -> None:
    """Erik Flowers' Weather Icons: heavy single-tone shapes."""
    icons = {kind: to_gray(render(src / "svg" / f"{name}.svg"), lambda v: v) for kind, (_, _, name) in KINDS.items()}
    license_file = src / "LICENSE-OFL.txt"
    if not license_file.exists():
        license_file.write_text(
            "Weather Icons by Erik Flowers, https://github.com/erikflowers/weather-icons\n"
            "Icons licensed under the SIL Open Font License 1.1: https://scripts.sil.org/OFL\n"
        )
    save_set("bold", icons, license_file, "Weather Icons by Erik Flowers. https://github.com/erikflowers/weather-icons")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sources = Path(sys.argv[1])
    build_yr(sources / "metno")
    build_meteocons(sources / "meteocons")
    build_bold(sources / "erikflowers")
